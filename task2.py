#Task 2: Using the Math Module for Calculations
import math
n = int(input("enter nay number : "))

#  1. Square root of the number
ans = math.sqrt(n)
print("sqrt : ",ans)

# 2.Natural logarithm (log base e) of the number
ans = math.log(n)
print("log : ",ans)
# 3.  Sine of the number (in radians)

result = math.sin(n)
print(result)